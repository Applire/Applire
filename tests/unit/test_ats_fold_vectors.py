"""ADR-090 clause 2 — one shared vector file pins the audit's `_fold_variants`
to the frontend's TypeScript port (`foldVariants` in `lib/locate-in-preview.ts`).

`tests/files/ats_fold_vectors.json` is GENERATED from the Python function
(`python3 tests/unit/test_ats_fold_vectors.py --write`, PYTHONPATH=backend and
the hermetic env). This test re-derives every expected list from the live
function, so a change to the folds that is not regenerated fails here, and the
regenerated file then fails the TypeScript test until the port follows.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

VECTORS = Path(__file__).resolve().parents[1] / "files" / "ats_fold_vectors.json"

# Already-normalised phrases (the audit folds AFTER `_norm`).
NEEDLES: list[str] = [
    "code reviews",  # s-plural, strip
    "code review",  # s-plural, append
    "saas",  # too short to fold
    "k8s",
    "methodology",  # y -> ies
    "methodologies",  # ies -> y
    "zertifizierungen",  # ungen <-> ung
    "zertifizierung",
    "kommunikationen",  # ionen <-> ion
    "kommunikation",
    "qualitäten",  # täten <-> tät
    "qualität",
    "sicherheiten",  # heiten <-> heit
    "sicherheit",
    "genauigkeiten",  # keiten <-> keit
    "genauigkeit",
    "partnerschaften",  # schaften <-> schaft
    "partnerschaft",
    "optimierungen",  # ierungen <-> ier
    "optimierung",  # ierung <-> ier
    "optimier",
    "produktionen",  # ktionen <-> zier
    "produktion",  # ktion <-> zier
    "produzier",
    "ärzte",  # plain noun
    "ärzte team",
    "industrieller mittelstand",  # adjective declension
    "im industriellen mittelstand",
    "neuer mittelstand",  # stem too short: stays unfolded
    "digitale zertifizierung",  # one declinable slot + suffix pair
    "ai",  # too short
]


def _fold():
    from applire.services.ats_audit import _fold_variants

    return _fold_variants


def build_vectors() -> list[dict]:
    f = _fold()
    return [{"needle": n, "variants": f(n)} for n in NEEDLES]


def test_fold_vector_file_matches_python_fold():
    data = json.loads(VECTORS.read_text(encoding="utf-8"))
    f = _fold()
    assert data["source"] == "applire.services.ats_audit._fold_variants"
    assert len(data["vectors"]) >= 20
    for v in data["vectors"]:
        assert f(v["needle"]) == v["variants"], v


def test_fold_vector_file_is_current_with_the_generator():
    data = json.loads(VECTORS.read_text(encoding="utf-8"))
    assert data["vectors"] == build_vectors(), (
        "regenerate tests/files/ats_fold_vectors.json with --write"
    )


if __name__ == "__main__" and "--write" in sys.argv:
    VECTORS.write_text(
        json.dumps(
            {
                "source": "applire.services.ats_audit._fold_variants",
                "adr": "ADR-090 clause 2",
                "note": "Generated by tests/unit/test_ats_fold_vectors.py --write; read by the Python and the TypeScript test.",
                "vectors": build_vectors(),
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {VECTORS}")
