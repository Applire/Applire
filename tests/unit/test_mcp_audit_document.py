@pytest.mark.asyncio
async def test_stored_cv_computes_and_persists(seeded):
    from applire.mcp.server import audit_document
    from applire.models.cv import GeneratedCV

    with (
        patch("applire.mcp.server.get_db", return_value=_db_cm(seeded["db"])),
        patch("applire.mcp.server.get_provider", return_value=None),
    ):
        report = await audit_document(document_id=str(seeded["cv_id"]))

    assert report["document_id"] == str(seeded["cv_id"])
    assert report["document_kind"] == "cv"
    by_loc = {c["claim"]["location"]: c["verdict"]["verdict"] for c in report["claims"]}
    assert by_loc["summary[0]"] == "inflated"

    # persisted for the UI panel (backfills a pre-Tiramisu/NULL row)
    record = await seeded["db"].get(GeneratedCV, seeded["cv_id"])
    assert record.truthfulness_report is not None


@pytest.mark.asyncio
async def test_stored_cv_returns_persisted_report_without_recompute(seeded):
    from applire.mcp.server import audit_document
    from applire.models.cv import GeneratedCV

    session = seeded["db"]
    record = await session.get(GeneratedCV, seeded["cv_id"])
    sentinel = {"version": "1.0", "document_kind": "cv", "claims": [],
                "counts": {}, "stated_limit": "x",
                "generated_at": "2026-07-18T00:00:00Z"}
    record.truthfulness_report = sentinel
    await session.commit()

    with (
        patch("applire.mcp.server.get_db", return_value=_db_cm(session)),
        patch("applire.mcp.server.get_provider", return_value=None),
    ):
        report = await audit_document(document_id=str(seeded["cv_id"]))

    assert report["stated_limit"] == "x"  # the stored report, not a recompute


