@pytest.mark.asyncio
async def test_requires_exactly_one_input():
    from applire.mcp.server import audit_document

    for kwargs in ({}, {"document_id": str(uuid.uuid4()), "document_text": "x"}):
        with pytest.raises(McpError) as exc_info:
            await audit_document(**kwargs)
        assert exc_info.value.error.code == -32602


@pytest.mark.asyncio
async def test_external_text_no_prior_generate_call(seeded):
    """ADR-054 à la carte: raw agent-authored text audits against the vault —
    the trap document's inflation (bug class #1) is flagged deterministically."""
    from applire.mcp.server import audit_document

    with (
        patch("applire.mcp.server.get_db", return_value=_db_cm(seeded["db"])),
        patch("applire.mcp.server.get_provider", return_value=None),
    ):
        report = await audit_document(document_text=TRAP_DOCUMENT)

    assert report["document_kind"] == "external"
    assert report["stated_limit"]
    by_text = {c["claim"]["text"]: c["verdict"] for c in report["claims"]}
    inflated = by_text["Reduced manual effort by 70% via a compliance workflow"]
    assert inflated["verdict"] == "inflated"
    assert inflated["checker"] == "stance"
    # the honest bullet stays green
    assert by_text["Led a team of 12 engineers"]["verdict"] == "grounded"
    # bug class #2 (misattribution, #196): the verdict EXISTS since 2026-07-19
    # but cannot fire on raw text — extract_claims_from_text has no rendered-
    # position ids to stamp, so the matcher is silent on this door (documented
    # in the tool description). Stored generated documents ARE covered.
    fda = by_text["Prepared the FDA audit readiness programme"]
    assert fda["verdict"] in ("grounded", "unverifiable")


